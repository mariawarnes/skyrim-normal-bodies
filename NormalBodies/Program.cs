using Mutagen.Bethesda;
using Mutagen.Bethesda.Skyrim;
using Mutagen.Bethesda.Synthesis;

namespace NormalBodies;

public static class Program
{
    private static Lazy<Settings> _settings = null!;

    public static async Task<int> Main(string[] args)
    {
        return await SynthesisPipeline.Instance
            .AddPatch<ISkyrimMod, ISkyrimModGetter>(RunPatch)
            .SetAutogeneratedSettings("Settings", "settings.json", out _settings)
            .SetTypicalOpen(GameRelease.SkyrimSE, "NormalBodies.esp")
            .Run(args);
    }

    public static void RunPatch(IPatcherState<ISkyrimMod, ISkyrimModGetter> state)
    {
        var settings = _settings.Value;
        var patcher = new BodyPatcher(state.LinkCache, settings);
        var changes = patcher.Plan(state.LoadOrder.PriorityOrder.Npc().WinningOverrides());

        foreach (var change in changes)
        {
            var npc = state.PatchMod.Npcs.GetOrAddAsOverride(change.Npc);
            npc.Weight = change.NewWeight;
        }

        foreach (var group in changes.GroupBy(c => c.Type).OrderBy(g => g.Key))
        {
            var range = patcher.RangeFor(group.Key);
            Console.WriteLine($"{group.Key,-9} ({range.Min}-{range.Max}): {group.Count()} NPCs changed");
        }
        Console.WriteLine($"Total: {changes.Count} NPC weights changed.");
        Console.WriteLine("Remember to regenerate FaceGen for these NPCs (see README) or they will have neck seams.");

        foreach (var change in changes.OrderBy(c => c.Type).ThenBy(c => c.Npc.EditorID))
        {
            Console.WriteLine($"  {change.Type,-9} {change.Npc.EditorID ?? change.Npc.FormKey.ToString(),-40} {change.OldWeight,5:0} -> {change.NewWeight,3:0}");
        }
    }
}
